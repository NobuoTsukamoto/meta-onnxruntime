#!/usr/bin/env python3
"""Generate conf/onnxruntime-deps-<version>.inc for an ONNX Runtime release.

ONNX Runtime downloads its third-party dependencies with CMake FetchContent
while configuring, which bypasses the bitbake fetcher. This script turns the
dependencies of cmake/deps.txt of the release into SRC_URI entries: GitHub
archives become git entries pinned with SRCREV (the tag is resolved with
git ls-remote), anything else is a download pinned with a sha256 checksum.

Usage: scripts/update-onnxruntime-deps.py 1.30.0
"""

import hashlib
import os
import re
import subprocess
import sys
import time

# The dependencies (names in cmake/deps.txt) that the recipes need. This depends on
# the build configuration (EXTRA_OECMAKE), not on the release. If do_configure fails
# with a download error after an update, add the missing dependency here.
DEPS = """
    abseil_cpp date dlpack eigen flatbuffers json microsoft_gsl mp11 onnx pybind11
    pytorch_cpuinfo re2 safeint
    protobuf protoc_linux_x64 protoc_linux_aarch64
    googletest
""".split()

DEPS_TXT_URL = "https://raw.githubusercontent.com/microsoft/onnxruntime/v{}/cmake/deps.txt"


def run(*cmd):
    """Run cmd and return its output, retrying on errors (GitHub is occasionally flaky)."""
    for attempt in range(5):
        try:
            return subprocess.run(cmd, check=True, capture_output=True).stdout
        except subprocess.CalledProcessError as e:
            if attempt == 4:
                sys.exit(f"error: {' '.join(cmd)}: {e.stderr.decode().strip()}")
            time.sleep(2 ** attempt)


def commit_of(repo, ref):
    """Return the commit that a tag (or commit) of a GitHub repository points to."""
    if re.fullmatch(r"[0-9a-f]{40}", ref):
        return ref
    tag = f"refs/tags/{ref}"
    out = run("git", "ls-remote", f"https://github.com/{repo}.git", tag, tag + "^{}").decode()
    refs = dict(reversed(line.split("\t")) for line in out.splitlines())
    return refs.get(tag + "^{}") or refs[tag]  # an annotated tag is listed with its commit


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    deps = {}
    for line in run("curl", "-fsSL", DEPS_TXT_URL.format(sys.argv[1])).decode().splitlines():
        if line.strip() and not line.startswith("#"):
            name, url, sha1 = line.split(";")
            deps[name] = (url, sha1)

    git, files = [], []  # (name, repo, commit) and (name, url, filename, sha256)
    for name in DEPS:
        url, sha1 = deps[name]
        m = re.match(r"https://github\.com/([^/]+/[^/]+)/archive/(.+)", url)
        if m:
            # .../archive/refs/tags/<tag>.zip, .../archive/<commit>.zip or .../archive/<commit>/<file>.zip
            ref = m[2].removeprefix("refs/tags/").split("/")[0]
            git.append((name, m[1], commit_of(m[1], re.sub(r"\.(zip|tar\.gz)$", "", ref))))
        else:
            data = run("curl", "-fsSL", url)
            if hashlib.sha1(data).hexdigest() != sha1:
                sys.exit(f"error: {url}: SHA1 differs from deps.txt")
            files.append((name, url, f"{name}-{os.path.basename(url)}", hashlib.sha256(data).hexdigest()))

    layer = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(layer, "conf", f"onnxruntime-deps-{sys.argv[1]}.inc")
    with open(out, "w") as f:
        f.write(f"# Generated by scripts/update-onnxruntime-deps.py {sys.argv[1]}, do not edit.\n")
        f.write("# Third-party dependencies that ONNX Runtime's CMake would otherwise download\n")
        f.write("# during do_configure; see classes-recipe/onnxruntime-offline-deps.bbclass.\n\n")
        f.write('SRC_URI += " \\\n')
        for name, repo, _ in git:
            f.write(f"    git://github.com/{repo}.git;protocol=https;nobranch=1;name={name};"
                    f"destsuffix=ort-deps/{name} \\\n")
        for name, url, filename, _ in files:
            f.write(f"    {url};downloadfilename={filename};unpack=0;name={name} \\\n")
        f.write('"\n\n')
        for name, _, commit in git:
            f.write(f'SRCREV_{name} = "{commit}"\n')
        for name, _, _, sha256 in files:
            f.write(f'SRC_URI[{name}.sha256sum] = "{sha256}"\n')
        # bitbake requires this when SRC_URI has more than one git repository
        f.write('SRCREV_FORMAT .= "' + "".join(f"_{name}" for name, *_ in git) + '"\n')
        f.write("\n# Dependencies fetched with git (checked out in UNPACKDIR/ort-deps/<name>)\n")
        f.write('ORT_DEPS_GIT = "\\\n' + "".join(f"    {name} \\\n" for name, *_ in git) + '"\n')
        f.write("\n# Dependencies fetched as archives: <name>:<file in UNPACKDIR>\n")
        f.write('ORT_DEPS_FILES = "\\\n' + "".join(f"    {name}:{filename} \\\n" for name, _, filename, _ in files) + '"\n')
    print(f"wrote {os.path.relpath(out, layer)} ({len(git)} git, {len(files)} archive dependencies)")


if __name__ == "__main__":
    main()
